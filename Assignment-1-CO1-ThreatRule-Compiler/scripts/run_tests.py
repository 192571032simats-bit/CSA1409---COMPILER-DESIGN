"""Build the Flex scanner and execute reproducible lexical test cases."""

from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
SCANNER_DIR = ROOT / "LEX_Scanner"
EXE = ROOT / "threatrule.exe"
OUTPUT = ROOT / "Output_Files"


def run(command: list[str], cwd: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        command, cwd=cwd, text=True, capture_output=True, check=False, input=""
    )


def build() -> None:
    flex = run(["flex", "threatrule.l"], SCANNER_DIR)
    if flex.returncode:
        raise RuntimeError(f"Flex generation failed:\n{flex.stderr}")
    compiler = run(
        ["gcc", "-std=c99", "-O2", "-Wall", "-Wextra", "-o", str(EXE), "lex.yy.c"],
        SCANNER_DIR,
    )
    if compiler.returncode:
        raise RuntimeError(f"GCC compilation failed:\n{compiler.stderr}")


def main() -> int:
    build()
    OUTPUT.mkdir(exist_ok=True)
    cases = [
        ("valid", ROOT / "Input_Files" / "valid_rules.tr", [], 0),
        ("invalid", ROOT / "Input_Files" / "invalid_rules.tr", [], 1),
        ("boundary", ROOT / "Input_Files" / "boundary_cases.tr", [], 1),
        ("design_challenge", ROOT / "Input_Files" / "hash_cve_url_feed.tr", [], 0),
        ("design_challenge_legacy", ROOT / "Input_Files" / "hash_cve_url_feed.tr", ["--legacy"], 1),
        ("invalid_feed", ROOT / "Input_Files" / "invalid_feed.tr", [], 1),
    ]
    report: list[str] = [
        "Execution evidence generated by scripts/run_tests.py",
        "Scanner: Flex-generated LEX_Scanner/lex.yy.c, compiled with GCC.",
        "",
    ]
    failed = False
    for name, source, options, expected in cases:
        result = run([str(EXE), *options, str(source)], ROOT)
        (OUTPUT / f"{name}_tokens.txt").write_text(result.stdout, encoding="utf-8")
        (OUTPUT / f"{name}_errors.txt").write_text(result.stderr, encoding="utf-8")
        passed = result.returncode == expected
        report.append(
            f"{name}: {'PASS' if passed else 'FAIL'} "
            f"(exit={result.returncode}, expected={expected}, "
            f"tokens={sum(1 for line in result.stdout.splitlines() if ':' in line)}, "
            f"diagnostics={sum(1 for line in result.stderr.splitlines() if line.strip())})"
        )
        failed |= not passed

    sample = run([str(EXE), str(ROOT / "Input_Files" / "sample_rule.tr")], ROOT)
    (OUTPUT / "token_output.txt").write_text(sample.stdout, encoding="utf-8")
    (OUTPUT / "error_log.txt").write_text(sample.stderr, encoding="utf-8")
    symbols = run([str(EXE), "--quiet", "--symbols", str(ROOT / "Input_Files" / "sample_rule.tr")], ROOT)
    (OUTPUT / "symbol_table_output.txt").write_text(symbols.stdout, encoding="utf-8")
    empty = run([str(EXE), "--stats"], ROOT)
    report.append(f"empty_stdin: {'PASS' if empty.returncode == 0 else 'FAIL'} ({empty.stdout.strip()})")
    (OUTPUT / "parser_output.txt").write_text(
        "No parser is integrated in this lexical-analyzer build; syntax is discussed in the report.\n",
        encoding="utf-8",
    )
    (ROOT / "Test_Cases" / "test_results.md").write_text("\n".join(report) + "\n", encoding="utf-8")
    print("\n".join(report))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
